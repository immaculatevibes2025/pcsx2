#!/usr/bin/env python3
"""Generate src/font.c: a proportional font atlas (ASCII 32-126) for the GS.

Glyphs are white with the coverage in alpha (0..0x80, the GS's 1.0), so drawing tints them with any colour.
Usage: gen_font.py <out.c> <font.ttf> [pixel size]
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
COLS = 16
TEX_W = 512


def main(out_path, ttf, size):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent + 2
    cell_w = TEX_W // COLS
    rows = (LAST - FIRST + 1 + COLS - 1) // COLS
    tex_h = 1
    while tex_h < rows * cell_h:
        tex_h *= 2

    img = Image.new("L", (TEX_W, tex_h), 0)
    draw = ImageDraw.Draw(img)
    advances = []
    for i, code in enumerate(range(FIRST, LAST + 1)):
        ch = chr(code)
        x = (i % COLS) * cell_w
        y = (i // COLS) * cell_h
        draw.text((x + 1, y + 1), ch, font=font, fill=255)
        adv = int(round(font.getlength(ch)))
        assert adv + 2 <= cell_w, "glyph too wide for the cell: " + ch
        advances.append(adv)

    px = img.load()
    with open(out_path, "w") as out:
        out.write("// Generated by tools/gen_font.py - do not edit\n")
        out.write("const int g_font_tex_w = %d, g_font_tex_h = %d, g_font_cell_w = %d, g_font_cell_h = %d;\n"
                  % (TEX_W, tex_h, cell_w, cell_h))
        out.write("const int g_font_ascent = %d, g_font_first = %d, g_font_last = %d, g_font_cols = %d;\n"
                  % (ascent, FIRST, LAST, COLS))
        out.write("const unsigned char g_font_adv[%d] = {%s};\n" % (len(advances), ", ".join(map(str, advances))))
        # one byte of coverage per texel; expanded to RGBA at start-up
        out.write("const unsigned char g_font_alpha[%d] __attribute__((aligned(16))) = {\n" % (TEX_W * tex_h))
        for yy in range(tex_h):
            row = [px[xx, yy] for xx in range(TEX_W)]
            out.write("\t" + ",".join(str((v * 128 + 127) // 255) for v in row) + ",\n")
        out.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 20)
