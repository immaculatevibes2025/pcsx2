#!/usr/bin/env python3
"""Generate src/vags.c: PS2 ADPCM (VAG) test samples played through SPU2 voices.

These go through the SPU2 voice path (pitch + interpolation), unlike the streamed PCM tests, so they show the
difference between PCSX2's interpolation modes.
  vag_sweep: logarithmic sine sweep 100 Hz -> 10.5 kHz over 6 s, 22,050 Hz
  vag_noise: white noise, 3 s, 22,050 Hz
"""
import math
import random
import struct
import sys

RATE = 22050
COEF = [(0, 0), (60, 0), (115, -52), (98, -55), (122, -60)]


def encode_block(samples, s1, s2):
    """Encode 28 samples. Returns (16 bytes without flags, new s1, new s2, error)."""
    best = None
    for f, (c1, c2) in enumerate(COEF):
        for shift in range(13):
            p1, p2 = s1, s2
            nibbles = []
            err = 0.0
            for x in samples:
                pred = (p1 * c1 + p2 * c2) / 64.0
                q = max(-8, min(7, int(round((x - pred) * (1 << shift) / 4096.0))))
                # decode exactly like the SPU2
                d = ((q << 12) >> shift) + ((p1 * c1 + p2 * c2 + 32) >> 6)
                d = max(-32768, min(32767, d))
                err += (x - d) ** 2
                p2, p1 = p1, d
                nibbles.append(q & 0xF)
            if best is None or err < best[0]:
                best = (err, f, shift, nibbles, p1, p2)
    err, f, shift, nibbles, p1, p2 = best
    data = bytes([(f << 4) | shift, 0]) + bytes(nibbles[i] | (nibbles[i + 1] << 4) for i in range(0, 28, 2))
    return data, p1, p2, err


def make_vag(samples, name):
    while len(samples) % 28:
        samples.append(0)
    body = bytearray(16)  # leading silent block, as in standard VAG files
    s1 = s2 = 0
    sig = noise = 0.0
    nblocks = len(samples) // 28
    for b in range(nblocks):
        blk = samples[b * 28:(b + 1) * 28]
        data, s1, s2, err = encode_block(blk, s1, s2)
        flags = 1 if b == nblocks - 1 else 0  # loop end, no repeat: voice stops
        body += bytes([data[0], flags]) + data[2:]
        sig += sum(x * x for x in blk)
        noise += err
    header = b"VAGp" + struct.pack(">IIII", 0x20, 0, len(body), RATE) + bytes(12) + name.encode()[:16].ljust(16, b"\0")
    snr = 10 * math.log10(sig / max(noise, 1e-9))
    return header + bytes(body), snr


def main(out_path):
    n = RATE * 6
    sweep = []
    f0, f1 = 100.0, 10500.0
    k = math.log(f1 / f0)
    for i in range(n):
        t = i / RATE
        phase = 2 * math.pi * f0 * 6.0 / k * (math.exp(k * t / 6.0) - 1)
        env = min(1.0, i / 480, (n - i) / 480)
        sweep.append(int(16000 * env * math.sin(phase)))
    rnd = random.Random(7)
    m = RATE * 3
    noise = [int(9000 * min(1.0, i / 480, (m - i) / 480) * rnd.uniform(-1, 1)) for i in range(m)]

    with open(out_path, "w") as out:
        out.write("// Generated by tools/gen_vag.py - do not edit\n")
        for name, s in (("vag_sweep", sweep), ("vag_noise", noise)):
            vag, snr = make_vag(s, name)
            print("%s: %d bytes, ADPCM SNR %.1f dB" % (name, len(vag), snr), file=sys.stderr)
            out.write("unsigned char %s[%d] __attribute__((aligned(64))) = {\n" % (name, len(vag)))
            for i in range(0, len(vag), 24):
                out.write("\t" + ",".join(str(b) for b in vag[i:i + 24]) + ",\n")
            out.write("};\nconst int %s_size = %d;\n" % (name, len(vag)))


if __name__ == "__main__":
    main(sys.argv[1])
