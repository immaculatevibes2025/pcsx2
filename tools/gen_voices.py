#!/usr/bin/env python3
"""Generate src/voices.c: spoken test labels as 48 kHz mono s16 arrays.

Uses espeak-ng when available (the GitHub build installs it). Without it, each label becomes a short
tone so the program still builds and runs.
"""
import math
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import wave

LABELS = [
    "Front left",
    "Center",
    "Front right",
    "Surround right",
    "Surround left",
    "Both surrounds",
    "Between front left and center",
    "Between center and front right",
    "Surround left, game mix A",
    "Surround left, game mix B",
    "Surround right, game mix B",
    "Circle sweep",
    "Subwoofer",
    "Ambience",
]

RATE = 48000


def resample(samples, src_rate):
    if src_rate == RATE:
        return samples
    out = []
    ratio = src_rate / RATE
    n = int(len(samples) / ratio)
    for i in range(n):
        p = i * ratio
        j = int(p)
        f = p - j
        a = samples[j]
        b = samples[j + 1] if j + 1 < len(samples) else a
        out.append(int(a + (b - a) * f))
    return out


def normalise(samples, peak=0.9):
    m = max(1, max(abs(s) for s in samples))
    g = peak * 32767 / m
    return [max(-32768, min(32767, int(s * g))) for s in samples]


def speak(text, tmp):
    path = os.path.join(tmp, "v.wav")
    subprocess.run(["espeak-ng", "-v", "en-us", "-s", "150", "-a", "200", "-w", path, text], check=True)
    with wave.open(path, "rb") as w:
        rate = w.getframerate()
        ch = w.getnchannels()
        data = w.readframes(w.getnframes())
    samples = list(struct.unpack("<%dh" % (len(data) // 2), data))
    if ch == 2:
        samples = samples[::2]
    # trim leading/trailing silence
    thr = 300
    start = next((i for i, s in enumerate(samples) if abs(s) > thr), 0)
    end = len(samples) - next((i for i, s in enumerate(reversed(samples)) if abs(s) > thr), 0)
    return normalise(resample(samples[start:end], rate))


def tone(idx):
    n = int(RATE * 0.35)
    f = 600 + 60 * idx
    return [int(20000 * math.sin(2 * math.pi * f * i / RATE) * min(1, i / 480, (n - i) / 480)) for i in range(n)]


def main(out_path):
    have = shutil.which("espeak-ng") is not None
    if not have:
        print("espeak-ng not found: using placeholder tones for the spoken labels", file=sys.stderr)
    with tempfile.TemporaryDirectory() as tmp, open(out_path, "w") as out:
        out.write("// Generated by tools/gen_voices.py - do not edit\n#include \"audio.h\"\n\n")
        for i, text in enumerate(LABELS):
            s = speak(text, tmp) if have else tone(i)
            out.write("static const short voice_%02d[%d] = {\n" % (i, len(s)))
            for k in range(0, len(s), 16):
                out.write("\t" + ", ".join(str(v) for v in s[k:k + 16]) + ",\n")
            out.write("};\n\n")
        out.write("const struct VoiceClip g_voices[%d] = {\n" % len(LABELS))
        for i in range(len(LABELS)):
            out.write("\t{voice_%02d, sizeof(voice_%02d) / sizeof(short)},\n" % (i, i))
        out.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1])
